/** A README without its title, which the page states itself. */
function readme(dir: string): { body: string } | null {
	const file = path.join(dir, "README.md");
	if (!existsSync(file)) return null;
	return { body: readFileSync(file, "utf8").replace(/^#\s+.+\n+/, "") };
}

/**
 * Markdown from the repository, as a page here shows it: relative links point at the file on
 * GitHub, and the text reads with First names. GitHub URLs keep the paths the files have on main,
 * so a link never points at a file that doesn't exist yet.
 */
function prose(markdown: string, from: string): string {
	const urls: string[] = [];
	const held = repoLinks(markdown, from).replace(/\]\((https:\/\/github\.com\/[^)\s]+)\)/g, (_, url: string) => `](\u0000${urls.push(url) - 1}\u0000)`);
	return toTypedPress(held).replace(/\u0000(\d+)\u0000/g, (_, i: string) => urls[Number(i)]!);
}

/**
 * Relative links in a README point into the repository on GitHub. Code is left as written:
 * `obj[sym](x)` in a code span or fence is a call, not a link.
 */
function repoLinks(markdown: string, from: string): string {
	return markdown
		.split(/(```[\s\S]*?```|`[^`\n]*`)/)
		.map((part, i) =>
			i % 2 === 1
				? part
				: part.replace(/\]\((?!https?:|#|mailto:)([^)\s]+)\)/g, (_, target: string) => {
						const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(from), target));
						return `](${resolved.endsWith("/") || !path.extname(resolved) ? tree : github}/${resolved.replace(/\/$/, "")})`;
					}),
		)
		.join("");
}

function compileSummary(name: string, dir: string): { ok: boolean; text: string; counts?: Record<string, number> } {
	const result = compiler.compile({ name, files: sources(dir), previous: null });
	if (!result.output) {
		const first = result.check.diagnostics[0];
		const where = first?.location ? `${first.location.file}:${first.location.line}:${first.location.column}` : "";
		return { ok: false, text: toTypedPress(`${first?.code ?? ""} ${where} ${first?.message ?? ""}`.trim()) };
	}
	return { ok: true, text: `${result.output.migrations.map(([file]) => file).join(", ")}` };
}

// The examples the site shows (lib/site-examples.ts). Each page holds the example's README, if it
// has one, and a file browser with every file the developer writes and every file `typedpress build`
// writes for them. The other directories under examples/ stay in the repository.
for (const { name } of siteExamples) {
	const dir = path.join(repo, "examples", name);
	// The compiler reads an example's npm packages as sources, so its locked packages must be there.
	if (existsSync(path.join(dir, "package-lock.json")) && !existsSync(path.join(dir, "node_modules"))) {
		const installed = spawnSync("npm", ["ci", "--ignore-scripts", "--no-audit", "--no-fund"], { cwd: dir, stdio: "inherit" });
		if (installed.status !== 0) throw new Error(`npm ci failed in examples/${name}`);
	}
	const result = compileSummary(name, dir);
	if (!result.ok) throw new Error(`examples/${name} does not compile, so the site can't show it: ${result.text}`);
}

