// Config API: the declarations every config imports, types/typedpress/index.d.ts. Each exported function
// with its doc comment and signature, by the sections the file is divided into.
// ---------------------------------------------------------------------------------------------

const dts = read("types/typedpress/index.d.ts");
const sections: { title: string; items: { name: string; doc: string; signature: string }[] }[] = [];
{
	const lines = dts.split("\n");
	let doc: string[] = [];
	for (let i = 0; i < lines.length; i++) {
		const line = lines[i]!;
		const heading = /^\/\/ (\d+)\. (.+)$/.exec(line);
		if (heading && lines[i - 1]?.startsWith("// ----")) {
			sections.push({ title: heading[2]!.trim(), items: [] });
			continue;
		}
		if (/^\s*\/\*\*/.test(line)) {
			doc = [];
			let j = i;
			for (; j < lines.length; j++) {
				doc.push(lines[j]!);
				if (lines[j]!.includes("*/")) break;
			}
			i = j;
			continue;
		}
		const fn = /^export declare function (\w+)/.exec(line);
		const iface = /^export (?:interface|type) (\w+)/.exec(line);
		if ((fn || iface) && sections.length) {
			const name = (fn ?? iface)![1]!;
			let end = i;
			if (fn) {
				let depth = 0;
				for (; end < lines.length; end++) {
					for (const ch of lines[end]!) depth += ch === "(" || ch === "{" || ch === "<" ? 1 : ch === ")" || ch === "}" || ch === ">" ? -1 : 0;
					if (depth <= 0 && /;\s*$/.test(lines[end]!)) break;
				}
			}
			const text = doc.map((l) => l.replace(/^\s*\/\*\*\s?|\s*\*\/\s*$|^\s*\*\s?/g, "")).join(" ").replace(/\s+/g, " ").trim();
			const section = sections.at(-1)!;
			if (fn) {
				const existing = section.items.find((item) => item.name === name);
				const signature = lines.slice(i, end + 1).join("\n");
				if (existing) existing.signature += `\n${signature}`;
				else section.items.push({ name, doc: text, signature });
			} else if (text && (name === "ConfigInput" || name === "ColumnBuilder")) {
				section.items.push({ name, doc: text, signature: "" });
			}
			doc = [];
		} else if (line.trim() && !line.trim().startsWith("*") && !line.startsWith("//")) {
			doc = [];
		}
	}
}
