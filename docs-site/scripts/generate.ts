/** Generated files by path under docs-site/, with their contents. */
const out = new Map<string, string>();
// An MDX comment. `*/` inside a source path such as packages/*/CHANGELOG.md would end it early.
const banner = (from: string) => `{/* Generated by docs-site/scripts/generate.ts from ${from.replaceAll("*/", "*\\/")}. Do not edit. */}\n`;

function page(file: string, frontmatter: Record<string, unknown>, from: string, body: string) {
	const yaml = Object.entries(frontmatter)
		.map(([key, value]) => `${key}: ${typeof value === "string" ? JSON.stringify(value) : JSON.stringify(value)}`)
		.join("\n");
	out.set(file, `---\n${yaml}\n---\n\n${banner(from)}\n${body.trim()}\n`);
}

/**
 * Markdown for an MDX page: outside code, braces and angle brackets show as written instead of
 * starting an expression or a tag. Fenced blocks and inline code pass through unchanged.
 */
function mdx(text: string): string {
	return text
		.split(/(^```[\s\S]*?^```[^\n]*$|`[^`\n]+`)/m)
		.map((part, i) => (i % 2 === 1 ? part : part.replace(/[{}<>]/g, (c) => `\\${c}`)))
		.join("");
}

/** A table cell: code stays code, pipes are escaped. */
function cell(text: string): string {
	return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function fence(lang: string, code: string, meta = ""): string {
	const ticks = code.includes("```") ? "````" : "```";
	return `${ticks}${lang}${meta ? ` ${meta}` : ""}\n${code.replace(/\n$/, "")}\n${ticks}`;
}

