/** A README without its title, which the page states itself. */
function readme(dir: string): { body: string } | null {
	const file = path.join(dir, "README.md");
	if (!existsSync(file)) return null;
	return { body: readFileSync(file, "utf8").replace(/^#\s+.+\n+/, "") };
}

/**
 * Markdown from the repository, as a page here shows it: relative links point at the file on
 * GitHub, and the text reads with First names. GitHub URLs keep the paths the files have on main,
 * so a link never points at a file that doesn't exist yet.
 */
function prose(markdown: string, from: string): string {
	const urls: string[] = [];
	const held = repoLinks(markdown, from).replace(/\]\((https:\/\/github\.com\/[^)\s]+)\)/g, (_, url: string) => `](\u0000${urls.push(url) - 1}\u0000)`);
	return toFirst(held).replace(/\u0000(\d+)\u0000/g, (_, i: string) => urls[Number(i)]!);
}

/** Relative links in a README point into the repository on GitHub. */
function repoLinks(markdown: string, from: string): string {
	return markdown.replace(/\]\((?!https?:|#|mailto:)([^)\s]+)\)/g, (_, target: string) => {
		const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(from), target));
		return `](${resolved.endsWith("/") || !path.extname(resolved) ? tree : github}/${resolved.replace(/\/$/, "")})`;
	});
}

function compileSummary(name: string, dir: string): { ok: boolean; text: string; counts?: Record<string, number> } {
	const result = compiler.compile({ name, files: sources(dir), previous: null });
	if (!result.output) {
		const first = result.check.diagnostics[0];
		const where = first?.location ? `${first.location.file}:${first.location.line}:${first.location.column}` : "";
		return { ok: false, text: toFirst(`${first?.code ?? ""} ${where} ${first?.message ?? ""}`.trim()) };
	}
	return { ok: true, text: `${result.output.migrations.map(([file]) => file).join(", ")}` };
}

