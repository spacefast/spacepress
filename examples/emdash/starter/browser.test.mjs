import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { submitSignIn } from '../sign-in.mjs';
import { cleanup, makeProject, start } from './local.mjs';

test('native admin saves and public search/theme controls work in Chromium', { timeout: 600000 }, async (t) => {
  const evidence = await mkdtemp(join(tmpdir(), 'typedpress-emdash-publishing-browser-'));
  console.log(`Browser evidence: ${evidence}`);
  const project = await makeProject('blog');
  t.after(async () => {
    const proof = await cleanup(project);
    await writeFile(join(evidence, 'cleanup.json'), JSON.stringify(proof, null, 2));
  });
  const receipt = await start(project, 'blog');
  await writeFile(join(evidence, 'receipt.json'), JSON.stringify(receipt, null, 2));
  const browser = await chromium.launch({ headless: true });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(60000);
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(`${receipt.base}/wp-login.php`);
  await submitSignIn(page, 'admin', 'typedpress-test-admin');
  await page.waitForURL(/\/wp-admin\//);
  await page.goto(`${receipt.base}/wp-admin/edit.php?post_type=tp_posts`);
  const row = page.locator('#the-list tr').filter({ has: page.locator('.row-title') }).first();
  const rowId = await row.getAttribute('id');
  assert.match(rowId, /^post-\d+$/);
  await row.hover();
  await row.locator('button.editinline').click();
  const editor = page.locator(`#edit-${rowId.slice('post-'.length)}`);
  const title = 'A browser-saved field note';
  await editor.locator('input[name=post_title]').fill(title);
  await page.screenshot({ path: join(evidence, 'native-quick-edit.png'), fullPage: true });
  await editor.locator('button.save').click();
  await expect(page.locator(`#${rowId} .row-title`)).toHaveText(title, { timeout: 60000 });
  await page.goto(`${receipt.base}/`);
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.screenshot({ path: join(evidence, 'blog-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Dark', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Dark', exact: true })).toHaveAttribute('aria-pressed', 'true');
  assert.equal(await page.locator('html').evaluate((element) => getComputedStyle(element).colorScheme), 'dark');
  await page.getByRole('button', { name: 'System', exact: true }).click();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'system');
  await page.getByRole('searchbox', { name: 'Search posts and pages' }).fill(title);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.waitForURL(/\/search\?q=/);
  const result = page.locator('.card').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
  await result.getByRole('heading', { name: title, exact: true }).click();
  await page.waitForURL(/\/posts\/the-pleasure-of-a-small-beginning\/?$/);
  await expect(page.locator('h1')).toHaveText(title);
  await expect(page.locator('.prose')).toContainText('starts with paying attention');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${receipt.base}/`);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Mobile page has no horizontal overflow.');
  await page.screenshot({ path: join(evidence, 'blog-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile(join(evidence, 'results.json'), JSON.stringify({ nativeQuickEdit: true, savedTitlePublic: true, themeReload: true, searchNavigation: true, mobileOverflow: false, pageErrors: errors }, null, 2));
});
