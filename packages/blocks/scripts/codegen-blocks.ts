// Generate `src/blocks.generated.ts`: one typed component per core block WordPress 7.1
// registers, with its attributes typed from the registry the serializer validates against.
//
//   node scripts/codegen-blocks.ts --write    regenerate the file
//   node scripts/codegen-blocks.ts            parity check: exit 1 when the committed file differs
//
// The registry is the prebundled @wordpress/block-library at the pinned version, so the
// generated types and the serializer's checks are one definition: what TypeScript accepts
// is what `createBlock()` will be given.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { withBlockApi } from "../src/compiler/serialize.ts";

interface Schema {
  type?: string | string[];
  enum?: unknown[];
  role?: string;
  default?: unknown;
}

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, "..", "src", "blocks.generated.ts");

/** `core/post-featured-image` → `PostFeaturedImage`. */
function pascal(blockName: string): string {
  return blockName.slice("core/".length).split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
}

/** The TypeScript type of one attribute, following the registry's vocabulary and the serializer's checks. */
function tsType(schema: Schema): string {
  if (schema.enum && schema.enum.length > 0 && schema.enum.every((entry) => entry === null || typeof entry !== "object")) {
    return schema.enum.map((entry) => JSON.stringify(entry)).join(" | ");
  }
  const types = schema.type === undefined ? [] : Array.isArray(schema.type) ? schema.type : [schema.type];
  if (types.length === 0) return "unknown";
  const mapped = types.map((type) => {
    switch (type) {
      case "string":
      case "rich-text":
        return "string";
      case "number":
      case "integer":
        return "number";
      case "boolean":
        return "boolean";
      case "array":
        return "readonly unknown[]";
      case "object":
        return "BlockObjectAttribute";
      case "null":
        return "null";
      default:
        return "unknown";
    }
  });
  return [...new Set(mapped)].join(" | ");
}

function identifier(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function render(): string {
  return withBlockApi((api) => {
    const types = api.getBlockTypes().filter((type) => type.name.startsWith("core/")).sort((a, b) => (a.name < b.name ? -1 : 1));
    const versions = JSON.parse(readFileSync(path.join(here, "..", "vendor", "versions.json"), "utf8")) as Record<string, string>;
    const lines: string[] = [
      "// GENERATED by scripts/codegen-blocks.ts from the pinned @wordpress/block-library. Do not edit.",
      `// @wordpress/block-library ${versions["@wordpress/block-library"]}, @wordpress/blocks ${versions["@wordpress/blocks"]} (what WordPress 7.1 bundles).`,
      "//",
      "// One component per core block, with every attribute the registry declares except the",
      "// editor-local ones WordPress never saves (`role: \"local\"`), which the serializer refuses.",
      "// Structured attributes are `BlockObjectAttribute`: a plain object whose shape belongs to WordPress.",
      'import { blockComponent } from "./component.ts";',
      'import type { BlockObjectAttribute } from "./nodes.ts";',
      "",
      "export type { BlockObjectAttribute };",
      "",
    ];
    const entries: string[] = [];
    for (const type of types) {
      const name = pascal(type.name);
      const attributes = Object.entries((type.attributes ?? {}) as Record<string, Schema>)
        .filter(([attributeName, schema]) => !(schema.role === "local" && !(type.name === "core/html" && attributeName === "content")))
        .sort(([a], [b]) => (a < b ? -1 : 1));
      lines.push(`/** Props of \`Core.${name}\`: the attributes of \`${type.name}\`. */`);
      lines.push(`export interface ${name}Props {`);
      for (const [attributeName, schema] of attributes) lines.push(`  ${identifier(attributeName)}?: ${tsType(schema)} | undefined;`);
      lines.push("}");
      lines.push("");
      entries.push(`  /** \`${type.name}\` */\n  ${name}: blockComponent<${name}Props>(${JSON.stringify(type.name)}),`);
    }
    lines.push("/** Every core block WordPress 7.1 registers, as a typed component. */");
    lines.push("export const Core = {");
    lines.push(...entries);
    lines.push("} as const;");
    lines.push("");
    lines.push("export type CoreBlockName = keyof typeof Core;");
    lines.push("");
    return lines.join("\n");
  }) as unknown as string;
}

const generated = await (render() as unknown as Promise<string>);
if (process.argv.includes("--write")) {
  writeFileSync(target, generated);
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
} else {
  let committed = "";
  try {
    committed = readFileSync(target, "utf8");
  } catch {
    /* missing counts as different */
  }
  if (committed !== generated) {
    console.error(`${path.relative(process.cwd(), target)} is out of date; run: node scripts/codegen-blocks.ts --write`);
    process.exit(1);
  }
  console.log(`${path.relative(process.cwd(), target)} is up to date`);
}
