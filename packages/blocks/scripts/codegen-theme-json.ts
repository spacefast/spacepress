// Generate `src/theme/theme-json.generated.d.ts` from the official WordPress 7.1 theme.json
// schema committed at `schemas/theme-7.1.json`.
//
//   node scripts/codegen-theme-json.ts --write    regenerate the file
//   node scripts/codegen-theme-json.ts            parity check: exit 1 when the committed file differs
//
// The same schema file is what the compiler validates an emitted theme.json against (ajv),
// so what the editor completes and what the build accepts are one definition.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile, type JSONSchema } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaPath = path.join(here, "..", "schemas", "theme-7.1.json");
const target = path.join(here, "..", "src", "theme", "theme-json.generated.d.ts");

const schema = JSON.parse(readFileSync(schemaPath, "utf8")) as JSONSchema;
const body = await compile(schema, "ThemeJson", {
  bannerComment: "",
  additionalProperties: false,
  strictIndexSignatures: true,
  // Deterministic output: no formatter run, whose version could change the text.
  format: false,
  style: { printWidth: 120 },
});
const generated = [
  "// GENERATED by scripts/codegen-theme-json.ts from schemas/theme-7.1.json (https://schemas.wp.org/wp/7.1/theme.json). Do not edit.",
  "/* eslint-disable */",
  "",
  body.replace(/\r\n/g, "\n").trimEnd(),
  "",
  "/** The document `theme.json` (version 3) and a style variation file both are. */",
  "export type ThemeJson = JSONSchemaForWordPressBlockThemeGlobalSettingsAndStyles;",
  "",
].join("\n");

if (process.argv.includes("--write")) {
  writeFileSync(target, generated);
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
} else {
  let committed = "";
  try {
    committed = readFileSync(target, "utf8");
  } catch {
    /* missing counts as different */
  }
  if (committed !== generated) {
    console.error(`${path.relative(process.cwd(), target)} is out of date; run: node scripts/codegen-theme-json.ts --write`);
    process.exit(1);
  }
  console.log(`${path.relative(process.cwd(), target)} is up to date`);
}
