import { lstat, mkdir, mkdtemp, readFile, realpath, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import tailwind from '@tailwindcss/vite';
import { build } from 'vite';

const assetDirectory = 'typedpress-assets';
const marker = '.typedpress-frontend';
const generatedHeader = '// Generated by typedpress-frontend.\n';
const entryName = /^[a-z][a-z0-9_-]*$/;

async function statIfPresent(file) {
  try {
    return await lstat(file);
  } catch (error) {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  }
}

async function ensureDirectory(directory) {
  try {
    await mkdir(directory);
  } catch (error) {
    if (error.code !== 'EEXIST') throw error;
    if (!(await lstat(directory)).isDirectory()) {
      throw new Error(`Expected a directory at ${directory}.`);
    }
  }
}

function entryMetadata(manifest, name, source) {
  const entry = manifest[source];
  if (!entry?.isEntry) throw new Error(`Vite did not emit the "${name}" entry (${source}).`);
  const url = (file) => `/${assetDirectory}/${file}`;
  const visited = new Set();
  const styles = new Set();
  function visit(chunk) {
    if (visited.has(chunk)) return;
    visited.add(chunk);
    for (const dependency of chunk.imports ?? []) visit(manifest[dependency]);
    for (const style of chunk.css ?? []) styles.add(style);
  }
  visit(entry);
  if (entry.file.endsWith('.css')) styles.add(entry.file);
  return {
    scripts: entry.file.endsWith('.css') ? [] : [url(entry.file)],
    links: [...styles].map((file) => ({ rel: 'stylesheet', href: url(file) })),
  };
}

export async function buildFrontend({
  root = process.cwd(),
  entries = { main: 'browser/index.ts' },
} = {}) {
  root = await realpath(root);
  const requested = Object.entries(entries);
  if (!requested.length) throw new Error('Declare at least one frontend entry.');
  const inputs = await Promise.all(requested.map(async ([name, file]) => {
    if (!entryName.test(name)) throw new Error(`Invalid frontend entry name "${name}".`);
    const absolute = await realpath(path.resolve(root, file));
    const relative = path.relative(root, absolute);
    if (path.isAbsolute(file) || !relative || relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
      throw new Error(`Frontend entry "${name}" must be relative to the project.`);
    }
    return [name, relative];
  }));
  if (new Set(inputs.map(([, file]) => file)).size !== inputs.length) {
    throw new Error('Each frontend entry must have a different input file.');
  }

  const publicDir = path.join(root, 'public');
  const typedpress = path.join(root, 'tp');
  const generated = path.join(typedpress, '_generated');
  await ensureDirectory(publicDir);
  await ensureDirectory(typedpress);
  await ensureDirectory(generated);

  const lock = path.join(generated, '.frontend-lock');
  await mkdir(lock).catch((error) => {
    if (error.code !== 'EEXIST') throw error;
    throw new Error(`Frontend build already running. If it stopped unexpectedly, check ${lock} before removing the lock.`);
  });
  try {
    return await compileFrontend({ root, inputs, publicDir, generated });
  } finally {
    await rm(lock, { recursive: true });
  }
}

async function compileFrontend({ root, inputs, publicDir, generated }) {
  const destination = path.join(publicDir, assetDirectory);
  const metadataFile = path.join(generated, 'frontend.ts');
  const previous = await statIfPresent(destination);
  if (previous && (!previous.isDirectory() || !(await statIfPresent(path.join(destination, marker)))?.isFile())) {
    throw new Error(`public/${assetDirectory} is reserved for generated frontend files. Move the existing path first.`);
  }
  const previousMetadata = await statIfPresent(metadataFile);
  if (previousMetadata && (!previousMetadata.isFile() || !(await readFile(metadataFile, 'utf8')).startsWith(generatedHeader))) {
    throw new Error('tp/_generated/frontend.ts is reserved for generated metadata. Move the existing file first.');
  }

  const staging = await mkdtemp(path.join(generated, '.frontend-'));
  const output = path.join(staging, 'assets');
  const backup = path.join(staging, 'previous');
  let preserveBackup = false;
  try {
    await build({
      root,
      configFile: false,
      base: './',
      publicDir: false,
      envPrefix: 'PUBLIC_',
      plugins: [tailwind()],
      oxc: { jsx: { runtime: 'automatic' } },
      resolve: { alias: { '@': path.join(root, 'src') }, dedupe: ['react', 'react-dom'] },
      build: {
        outDir: output,
        manifest: true,
        reportCompressedSize: false,
        rolldownOptions: { input: Object.fromEntries(inputs.map(([name, file]) => [name, path.resolve(root, file)])) },
      },
    });

    const manifestFile = path.join(output, '.vite', 'manifest.json');
    const manifest = JSON.parse(await readFile(manifestFile, 'utf8'));
    const result = Object.fromEntries(inputs.map(([name, file]) => [
      name,
      entryMetadata(manifest, name, file.split(path.sep).join('/')),
    ]));
    await rm(path.dirname(manifestFile), { recursive: true });
    await writeFile(path.join(output, marker), '');
    const metadata = path.join(staging, 'frontend.ts');
    await writeFile(metadata, `${generatedHeader}export const frontend = ${JSON.stringify(result, null, 2)};\n`);

    if (previous) await rename(destination, backup);
    try {
      await rename(output, destination);
      try {
        await rename(metadata, metadataFile);
      } catch (error) {
        await rename(destination, output);
        throw error;
      }
    } catch (error) {
      if (previous) {
        try {
          await rename(backup, destination);
        } catch (restoreError) {
          preserveBackup = true;
          throw new AggregateError([error, restoreError], `The previous frontend build is at ${backup}.`);
        }
      }
      throw error;
    }
    return result;
  } finally {
    if (!preserveBackup) await rm(staging, { recursive: true, force: true });
  }
}
