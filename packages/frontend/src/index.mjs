import { link, lstat, mkdir, mkdtemp, readFile, readdir, realpath, rename, rm, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { createServer as createHttpServer } from 'node:http';
import { createRequire } from 'node:module';
import path from 'node:path';
import tailwind from '@tailwindcss/vite';
import { build, createFilter, createServer, normalizePath, transformWithOxc } from 'vite';

const assetDirectory = 'typedpress-assets';
const styleDirectory = 'typedpress-styles';
const marker = '.typedpress-frontend';
// What buildFrontend was last asked to build here: `typedpress build`, `push` and `dev` read it.
const record = '.tp/frontend-dev.json';
// Every address Vite serves in `typedpress dev` is below this path, so a proxy in front of the site can
// mount it on the site's own address.
const devBase = '/__tp_vite';
const generatedHeader = '// Generated by typedpress-frontend.\n';
const entryName = /^[a-z][a-z0-9_-]*$/;
const resourceQuery = /[?&](?:raw|url|worker|sharedworker|inline|no-inline)(?:=|&|$)/;
const patterns = (root, globs = []) => globs.map((glob) => normalizePath(path.resolve(root, glob)));
const frontendResolve = (root) => ({
  alias: { '@': path.join(root, 'src') },
  dedupe: ['react', 'react-dom', 'preact', 'solid-js', 'vue'],
});

async function statIfPresent(file) {
  try {
    return await lstat(file);
  } catch (error) {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  }
}

async function ensureDirectory(directory) {
  try {
    await mkdir(directory);
  } catch (error) {
    if (error.code !== 'EEXIST') throw error;
    if (!(await lstat(directory)).isDirectory()) {
      throw new Error(`Expected a directory at ${directory}.`);
    }
  }
}

// A process that has exited (killed by Ctrl+C, say) holds no lock. EPERM is a live process of
// another user's.
function running(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return error.code === 'EPERM';
  }
}

// The lock file names the process that holds it. It is linked into place whole, so a reader never
// sees it without that process ID, and a lock whose process is gone (or one from before the file
// held an ID) is taken over.
async function lock(file) {
  const mine = `${file}-${process.pid}-${randomUUID()}`;
  await writeFile(mine, `${process.pid}\n`);
  try {
    for (;;) {
      try {
        await link(mine, file);
        return;
      } catch (error) {
        if (error.code !== 'EEXIST') throw error;
      }
      const holder = Number.parseInt(await readFile(file, 'utf8').catch(() => ''), 10);
      if (Number.isInteger(holder) && holder > 0 && running(holder)) {
        throw new Error(`Frontend build already running (process ${holder}). If no such build is running, remove ${file}.`);
      }
      await rm(file, { recursive: true, force: true });
    }
  } finally {
    await rm(mine, { force: true });
  }
}

async function entryMetadata(manifest, name, source, output) {
  const entry = manifest[source];
  if (!entry?.isEntry) throw new Error(`Vite did not emit the "${name}" entry (${source}).`);
  const url = (file) => `/${assetDirectory}/${file}`;
  const visited = new Set();
  const styles = new Set();
  function visit(chunk) {
    if (visited.has(chunk)) return;
    visited.add(chunk);
    for (const dependency of chunk.imports ?? []) visit(manifest[dependency]);
    for (const style of chunk.css ?? []) styles.add(style);
  }
  visit(entry);
  const stylesheetEntry = entry.file.endsWith('.css');
  if (stylesheetEntry) styles.add(entry.file);
  const links = [...styles].map((file) => ({ rel: 'stylesheet', href: url(file) }));
  if (stylesheetEntry) return { scripts: [], links };

  // WordPress versions the launcher. Every import of the Vite entry uses its bare hashed URL.
  const launcher = `entrypoints/${path.posix.basename(entry.file)}`;
  await writeFile(path.join(output, launcher), `import ${JSON.stringify(`../${entry.file}`)};\n`);
  links.push({ rel: 'modulepreload', href: url(entry.file) });
  return { scripts: [url(launcher)], links };
}

async function frameworkPlugins(root, frameworks) {
  const plugins = [];
  const preact = frameworks.preact?.length ? createFilter(patterns(root, frameworks.preact)) : undefined;
  const solid = frameworks.solid?.length ? patterns(root, frameworks.solid) : undefined;

  if (preact) {
    const isSolid = solid && createFilter(solid);
    plugins.push({
      name: 'typedpress:preact',
      enforce: 'pre',
      transform(code, id) {
        const filename = id.split(/[?#]/, 1)[0];
        if (resourceQuery.test(id) || !/\.[jt]sx$/.test(filename) || !preact(filename)) return;
        if (isSolid?.(filename)) this.error('A JSX file must match only one of the Preact and Solid include globs.');
        return transformWithOxc(code, filename, {
          jsx: { runtime: 'automatic', importSource: 'preact' },
          sourcemap: true,
        });
      },
    });
  }
  if (solid) {
    const { default: solidPlugin } = await import('vite-plugin-solid');
    // The Solid plugin applies its filter before stripping an import query.
    const include = solid.flatMap((glob) => [glob, `${glob}[?]*`]);
    plugins.push(solidPlugin({ include, exclude: resourceQuery, hot: false }), {
      name: 'typedpress:solid-browser-exports',
      configEnvironment: {
        order: 'post',
        handler(_name, config) {
          // The Solid JSX transform is scoped to the app's globs. Dependencies use their compiled exports.
          const resolve = config.resolve;
          if (resolve?.conditions) resolve.conditions = resolve.conditions.filter((condition) => condition !== 'solid');
        },
      },
    });
  }
  if (frameworks.vue) {
    const { default: vuePlugin } = await import('@vitejs/plugin-vue');
    const require = createRequire(path.join(root, 'package.json'));
    plugins.push(vuePlugin({ compiler: require('vue/compiler-sfc') }));
  }
  return plugins;
}

export async function buildFrontend({
  root = process.cwd(),
  entries = { main: 'browser/index.ts' },
  frameworks = {},
  logLevel = 'info',
} = {}) {
  root = await realpath(root);
  const requested = Object.entries(entries);
  if (!requested.length) throw new Error('Declare at least one frontend entry.');
  const inputs = await Promise.all(requested.map(async ([name, file]) => {
    if (!entryName.test(name)) throw new Error(`Invalid frontend entry name "${name}".`);
    const absolute = await realpath(path.resolve(root, file));
    const relative = path.relative(root, absolute);
    if (path.isAbsolute(file) || !relative || relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
      throw new Error(`Frontend entry "${name}" must be relative to the project.`);
    }
    return [name, relative];
  }));
  if (new Set(inputs.map(([, file]) => file)).size !== inputs.length) {
    throw new Error('Each frontend entry must have a different input file.');
  }

  return publishFrontend({ root, inputs, directory: assetDirectory, frameworks, logLevel, plugins: await frameworkPlugins(root, frameworks) });
}

/**
 * @internal `typedpress build`, `push` and `export` call this before they read `public/`: the browser
 * entries buildFrontend built in this project before, built again with the options it recorded.
 * `typedpress dev` serves the entries' sources through Vite and never rewrites the bundle, so without
 * this a later build would ship the bundle from before the session's edits. Answers false when
 * nothing was recorded (a fresh checkout, where the project's own build script runs first).
 */
export async function rebuildFrontend({ root = process.cwd() } = {}) {
  root = await realpath(root);
  let recorded;
  try { recorded = JSON.parse(await readFile(path.join(root, record), 'utf8')); }
  catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
  // An entry whose source was deleted since it was recorded is no longer built. With none left
  // the record is stale: it goes, and the build reads public/ as it is.
  const entries = [];
  for (const [name, entry] of Object.entries(recorded.entries ?? {})) {
    if (typeof entry?.source === 'string' && await statIfPresent(path.resolve(root, entry.source))) entries.push([name, entry.source]);
  }
  if (!entries.length) {
    await rm(path.join(root, record), { force: true });
    return false;
  }
  await buildFrontend({ root, entries: Object.fromEntries(entries), frameworks: recorded.frameworks ?? {}, logLevel: 'warn' });
  return true;
}

/**
 * @internal `typedpress dev` serves the original browser entries while it watches.
 *
 * Vite runs as middleware on an HTTP server made here, not on one of its own: a Vite that owns its
 * server also takes the process's SIGTERM and exits, which would skip `typedpress dev`'s cleanup and
 * leave WordPress running. `entries` maps an entry's name to its source file.
 */
export async function serveFrontend({ root, host, port = 0, site, reach, entries, frameworks = {} }) {
  const { default: react } = await import('@vitejs/plugin-react');
  const modules = new Map(Object.entries(entries).map(([name, entry]) => [`/@typedpress/${name}.js`, entry]));
  const token = randomUUID();
  const ping = `${devBase}/@typedpress/ping`;
  const http = createHttpServer();
  let vite;
  http.on('request', (request, response) => {
    // Answers who is listening here: `typedpress dev` asks through the site's address to learn
    // whether a proxy passes this path on.
    if (request.url === ping) {
      response.writeHead(200, { 'content-type': 'text/plain', 'cache-control': 'no-store' }).end(token);
    } else if (vite) {
      vite.middlewares(request, response, () => { response.writeHead(404).end(); });
    } else {
      response.writeHead(503).end();
    }
  });
  const close = async () => {
    await vite?.close();
    if (http.listening) await new Promise((done) => { http.close(done); http.closeAllConnections(); });
  };
  const listen = (wanted) => new Promise((done, fail) => {
    http.once('error', fail);
    http.listen(wanted, host, () => { http.off('error', fail); done(); });
  });
  // The port asked for is the one a proxy was pointed at; another is taken only when it is busy.
  await listen(port).catch((error) => {
    if (error.code !== 'EADDRINUSE' || port === 0) throw error;
    return listen(0);
  });
  const listening = http.address().port;
  let origin;
  try {
    // Where a browser that has the site open finds this server: '' for the site's own address,
    // an origin of this server's own, or null for nowhere. Nothing is served to nowhere.
    origin = await reach({ port: listening, ping, token });
  } catch (error) {
    await close();
    throw error;
  }
  if (origin === null) {
    await close();
    return { port: listening, paths: null, close: async () => {} };
  }
  try {
    vite = await createServer({
      root,
      base: `${devBase}/`,
      configFile: false,
      publicDir: false,
      appType: 'custom',
      envPrefix: 'PUBLIC_',
      resolve: frontendResolve(root),
      optimizeDeps: { entries: [...modules.values()].map((entry) => entry.source) },
      plugins: [tailwind(), react({ exclude: [resourceQuery, /\/node_modules\//, ...patterns(root, frameworks.preact), ...patterns(root, frameworks.solid)] }),
        ...await frameworkPlugins(root, frameworks), {
          name: 'typedpress:dev-launchers',
          resolveId(id) { if (modules.has(id)) return `\0${id}`; },
          load(id) {
            const entry = id.startsWith('\0') && modules.get(id.slice(1));
            if (!entry) return;
            // The page still links the built bundle's stylesheets and preload. Once this entry's
            // own modules have run (its styles are in the document), those links go: a rule
            // deleted from the source must not stay applied from the built file.
            return `import '/@vite/client';
import '@vitejs/plugin-react/preamble';
import ${JSON.stringify(`/${entry.source}`)};
const built = ${JSON.stringify(entry.links ?? [])};
for (const link of document.querySelectorAll('link[rel="stylesheet"], link[rel="modulepreload"]')) {
  const { pathname } = new URL(link.href, location.href);
  if (built.some((href) => pathname.endsWith(href))) link.remove();
}
`;
          },
        }],
      server: {
        // Vite as middleware on the server above. A Vite that makes its own server also takes the
        // process's SIGTERM and exits on it, past the caller's cleanup.
        middlewareMode: { server: http },
        ws: { server: http },
        // Addresses in stylesheets (fonts, images) resolve against the page: name this server.
        origin: origin || undefined,
        // The site's own name, for requests a proxy passes on from the site's address.
        allowedHosts: [new URL(site).hostname],
        cors: { origin: new URL(site).origin },
        fs: {
          // Keep Vite's default denials and exclude Studio's local WordPress and compiled artifacts.
          deny: ['.env', '.env.*', '*.{crt,pem,key,p12,pfx,cer,der}', '.npmrc', '.yarnrc.yml', '**/.git/**', '**/.tp/**', '**/tp/dist/**'],
        },
        watch: { ignored: ['**/.tp/**', '**/tp/_generated/**', '**/tp/dist/**', '**/public/typedpress-{assets,styles}/**'] },
      },
    });
    return {
      port: listening,
      paths: Object.fromEntries(Object.keys(entries).map((name) => [name, `${origin}${devBase}/@typedpress/${name}.js`])),
      // After the bundle was built again: its links have new names, which the next page load drops.
      update(built) {
        const graph = vite.environments.client.moduleGraph;
        for (const [name, entry] of Object.entries(built)) {
          const id = `/@typedpress/${name}.js`;
          if (!modules.has(id)) continue;
          modules.set(id, entry);
          const module = graph.getModuleById(`\0${id}`);
          if (module) graph.invalidateModule(module);
        }
      },
      close,
    };
  } catch (error) {
    await close();
    throw error;
  }
}

/** @internal Called by the native compiler while it holds the project build lock. */
export async function buildStyles({ root, styles }) {
  return publishFrontend({
    root: await realpath(root),
    inputs: styles.map((file, index) => [`style-${index}`, file]),
    directory: styleDirectory,
  });
}

async function publishFrontend({ root, inputs, directory, frameworks, logLevel = 'warn', plugins = [] }) {
  const publicDir = path.join(root, 'public');
  const typedpress = path.join(root, 'tp');
  const generated = path.join(typedpress, '_generated');
  await ensureDirectory(publicDir);
  await ensureDirectory(typedpress);
  await ensureDirectory(generated);

  const held = path.join(generated, `.${directory}-lock`);
  await lock(held);
  try {
    const output = await compileFrontend({ root, inputs, publicDir, generated, directory, plugins, logLevel });
    if (frameworks) {
      // Each entry's source, with the launchers and links this build gave it: enough to build it
      // again (rebuildFrontend) and to put Vite in the launchers' place (typedpress dev).
      const state = path.join(root, path.dirname(record));
      await ensureDirectory(state);
      const built = Object.fromEntries(inputs.map(([name, source]) => [name, {
        source: normalizePath(source), scripts: output[name].scripts, links: output[name].links.map((link) => link.href),
      }]));
      const temp = path.join(state, `frontend-dev-${randomUUID()}.json`);
      try {
        await writeFile(temp, JSON.stringify({ entries: built, frameworks }));
        await rename(temp, path.join(root, record));
      } finally {
        await rm(temp, { force: true });
      }
    }
    return output;
  } finally {
    await rm(held, { force: true });
  }
}

async function compileFrontend({ root, inputs, publicDir, generated, directory, plugins, logLevel }) {
  const stylesOnly = directory === styleDirectory;
  const destination = path.join(publicDir, directory);
  const metadataName = stylesOnly ? 'frontend-styles.json' : 'frontend.ts';
  const metadataFile = path.join(generated, metadataName);
  const header = stylesOnly ? '{"generatedBy":"typedpress-frontend","styles":' : generatedHeader;
  const previous = await statIfPresent(destination);
  if (previous && (!previous.isDirectory() || !(await statIfPresent(path.join(destination, marker)))?.isFile())) {
    throw new Error(`public/${directory} is reserved for generated frontend files. Move the existing path first.`);
  }
  const previousMetadata = await statIfPresent(metadataFile);
  if (previousMetadata) {
    const metadata = previousMetadata.isFile() ? await readFile(metadataFile, 'utf8') : '';
    const contents = stylesOnly ? metadata : metadata.replace(/^\uFEFF/, '').replace('\r\n', '\n');
    if (!contents.startsWith(header)) {
      throw new Error(`tp/_generated/${metadataName} is reserved for generated metadata. Move the existing file first.`);
    }
  }

  // A build that was stopped (Ctrl+C) leaves its staging directory. Under the lock no other build
  // of this directory is running, so one is removed unless it holds the previous build it could
  // not put back. `.frontend-` is the name 0.1.0 gave either kind.
  const prefix = `.${directory}-build-`;
  for (const name of await readdir(generated)) {
    const leftover = path.join(generated, name);
    if ((name.startsWith(prefix) || name.startsWith('.frontend-')) && !(await statIfPresent(path.join(leftover, 'previous')))) {
      await rm(leftover, { recursive: true, force: true });
    }
  }
  const staging = await mkdtemp(path.join(generated, prefix));
  const output = path.join(staging, 'assets');
  const backup = path.join(staging, 'previous');
  let preserveBackup = false;
  try {
    if (inputs.length) await build({
      root,
      configFile: false,
      logLevel,
      base: './',
      publicDir: false,
      envPrefix: 'PUBLIC_',
      plugins: [tailwind(), ...plugins],
      oxc: { jsx: { runtime: 'automatic' } },
      resolve: frontendResolve(root),
      build: {
        outDir: output,
        manifest: true,
        reportCompressedSize: false,
        rolldownOptions: { input: Object.fromEntries(inputs.map(([name, file]) => [name, path.resolve(root, file)])) },
      },
    });

    const result = {};
    if (inputs.length) {
      const manifestFile = path.join(output, '.vite', 'manifest.json');
      const manifest = JSON.parse(await readFile(manifestFile, 'utf8'));
      if (!stylesOnly) await mkdir(path.join(output, 'entrypoints'));
      for (const [name, file] of inputs) {
        const source = file.split(path.sep).join('/');
        if (stylesOnly) {
          const entry = manifest[source];
          if (!entry?.isEntry || !entry.file.endsWith('.css')) {
            throw new Error(`Vite did not emit the stylesheet ${source}.`);
          }
          result[source] = `/${directory}/${entry.file}`;
        } else {
          result[name] = await entryMetadata(manifest, name, source, output);
        }
      }
      await rm(path.dirname(manifestFile), { recursive: true });
    } else {
      await mkdir(output);
    }
    await writeFile(path.join(output, marker), '');
    const metadata = path.join(staging, metadataName);
    if (stylesOnly) {
      await writeFile(metadata, `${header}${JSON.stringify(result)}}\n`);
    } else {
      await writeFile(metadata, `${header}export const frontend = ${JSON.stringify(result, null, 2)};\n`);
    }

    if (previous) await rename(destination, backup);
    try {
      await rename(output, destination);
      try {
        await rename(metadata, metadataFile);
      } catch (error) {
        await rename(destination, output);
        throw error;
      }
    } catch (error) {
      if (previous) {
        try {
          await rename(backup, destination);
        } catch (restoreError) {
          preserveBackup = true;
          throw new AggregateError([error, restoreError], `The previous frontend build is at ${backup}.`);
        }
      }
      throw error;
    }
    return result;
  } finally {
    if (!preserveBackup) await rm(staging, { recursive: true, force: true });
  }
}
