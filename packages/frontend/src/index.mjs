import { lstat, mkdir, mkdtemp, readFile, realpath, rename, rm, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import path from 'node:path';
import tailwind from '@tailwindcss/vite';
import { build, createFilter, createServer, normalizePath, transformWithOxc } from 'vite';

const assetDirectory = 'typedpress-assets';
const styleDirectory = 'typedpress-styles';
const marker = '.typedpress-frontend';
const generatedHeader = '// Generated by typedpress-frontend.\n';
const entryName = /^[a-z][a-z0-9_-]*$/;
const resourceQuery = /[?&](?:raw|url|worker|sharedworker|inline|no-inline)(?:=|&|$)/;
const patterns = (root, globs = []) => globs.map((glob) => normalizePath(path.resolve(root, glob)));
const frontendResolve = (root) => ({
  alias: { '@': path.join(root, 'src') },
  dedupe: ['react', 'react-dom', 'preact', 'solid-js', 'vue'],
});

async function statIfPresent(file) {
  try {
    return await lstat(file);
  } catch (error) {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  }
}

async function ensureDirectory(directory) {
  try {
    await mkdir(directory);
  } catch (error) {
    if (error.code !== 'EEXIST') throw error;
    if (!(await lstat(directory)).isDirectory()) {
      throw new Error(`Expected a directory at ${directory}.`);
    }
  }
}

async function entryMetadata(manifest, name, source, output) {
  const entry = manifest[source];
  if (!entry?.isEntry) throw new Error(`Vite did not emit the "${name}" entry (${source}).`);
  const url = (file) => `/${assetDirectory}/${file}`;
  const visited = new Set();
  const styles = new Set();
  function visit(chunk) {
    if (visited.has(chunk)) return;
    visited.add(chunk);
    for (const dependency of chunk.imports ?? []) visit(manifest[dependency]);
    for (const style of chunk.css ?? []) styles.add(style);
  }
  visit(entry);
  const stylesheetEntry = entry.file.endsWith('.css');
  if (stylesheetEntry) styles.add(entry.file);
  const links = [...styles].map((file) => ({ rel: 'stylesheet', href: url(file) }));
  if (stylesheetEntry) return { scripts: [], links };

  // WordPress versions the launcher. Every import of the Vite entry uses its bare hashed URL.
  const launcher = `entrypoints/${path.posix.basename(entry.file)}`;
  await writeFile(path.join(output, launcher), `import ${JSON.stringify(`../${entry.file}`)};\n`);
  links.push({ rel: 'modulepreload', href: url(entry.file) });
  return { scripts: [url(launcher)], links };
}

async function frameworkPlugins(root, frameworks) {
  const plugins = [];
  const preact = frameworks.preact?.length ? createFilter(patterns(root, frameworks.preact)) : undefined;
  const solid = frameworks.solid?.length ? patterns(root, frameworks.solid) : undefined;

  if (preact) {
    const isSolid = solid && createFilter(solid);
    plugins.push({
      name: 'typedpress:preact',
      enforce: 'pre',
      transform(code, id) {
        const filename = id.split(/[?#]/, 1)[0];
        if (resourceQuery.test(id) || !/\.[jt]sx$/.test(filename) || !preact(filename)) return;
        if (isSolid?.(filename)) this.error('A JSX file must match only one of the Preact and Solid include globs.');
        return transformWithOxc(code, filename, {
          jsx: { runtime: 'automatic', importSource: 'preact' },
          sourcemap: true,
        });
      },
    });
  }
  if (solid) {
    const { default: solidPlugin } = await import('vite-plugin-solid');
    // The Solid plugin applies its filter before stripping an import query.
    const include = solid.flatMap((glob) => [glob, `${glob}[?]*`]);
    plugins.push(solidPlugin({ include, exclude: resourceQuery, hot: false }), {
      name: 'typedpress:solid-browser-exports',
      configEnvironment: {
        order: 'post',
        handler(_name, config) {
          // The Solid JSX transform is scoped to the app's globs. Dependencies use their compiled exports.
          const resolve = config.resolve;
          if (resolve?.conditions) resolve.conditions = resolve.conditions.filter((condition) => condition !== 'solid');
        },
      },
    });
  }
  if (frameworks.vue) {
    const { default: vuePlugin } = await import('@vitejs/plugin-vue');
    const require = createRequire(path.join(root, 'package.json'));
    plugins.push(vuePlugin({ compiler: require('vue/compiler-sfc') }));
  }
  return plugins;
}

export async function buildFrontend({
  root = process.cwd(),
  entries = { main: 'browser/index.ts' },
  frameworks = {},
} = {}) {
  root = await realpath(root);
  const requested = Object.entries(entries);
  if (!requested.length) throw new Error('Declare at least one frontend entry.');
  const inputs = await Promise.all(requested.map(async ([name, file]) => {
    if (!entryName.test(name)) throw new Error(`Invalid frontend entry name "${name}".`);
    const absolute = await realpath(path.resolve(root, file));
    const relative = path.relative(root, absolute);
    if (path.isAbsolute(file) || !relative || relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
      throw new Error(`Frontend entry "${name}" must be relative to the project.`);
    }
    return [name, relative];
  }));
  if (new Set(inputs.map(([, file]) => file)).size !== inputs.length) {
    throw new Error('Each frontend entry must have a different input file.');
  }

  return publishFrontend({ root, inputs, directory: assetDirectory, frameworks, plugins: await frameworkPlugins(root, frameworks) });
}

/** @internal Studio serves the original browser entries while typedpress dev is watching. */
export async function serveFrontend({ root, host, site, launchers, frameworks }) {
  const { default: react } = await import('@vitejs/plugin-react');
  const entries = new Map(Object.entries(launchers).map(([launcher, source]) => [`/__tp_vite${launcher}`, source]));
  const server = await createServer({
    root,
    configFile: false,
    publicDir: false,
    envPrefix: 'PUBLIC_',
    resolve: frontendResolve(root),
    optimizeDeps: { entries: [...entries.values()] },
    plugins: [tailwind(), react({ exclude: [resourceQuery, /\/node_modules\//, ...patterns(root, frameworks.preact), ...patterns(root, frameworks.solid)] }),
      ...await frameworkPlugins(root, frameworks), {
        name: 'typedpress:dev-launchers',
        resolveId(id) { if (entries.has(id)) return `\0${id}`; },
        load(id) {
          const entry = id.startsWith('\0') && entries.get(id.slice(1));
          if (!entry) return;
          return `import '/@vite/client';\nimport '@vitejs/plugin-react/preamble';\nimport ${JSON.stringify(`/${entry}`)};`;
        },
      }],
    server: {
      host,
      cors: { origin: site },
      fs: {
        // Keep Vite's default denials and exclude Studio's local WordPress and compiled artifacts.
        deny: ['.env', '.env.*', '*.{crt,pem,key,p12,pfx,cer,der}', '.npmrc', '.yarnrc.yml', '**/.git/**', '**/.tp/**', '**/tp/dist/**'],
      },
      watch: { ignored: ['**/.tp/**', '**/tp/_generated/**', '**/tp/dist/**', '**/public/typedpress-{assets,styles}/**'] },
    },
  });
  try {
    await server.listen();
    const { port } = server.httpServer.address();
    const origin = `http://${host.includes(':') ? `[${host}]` : host}:${port}`;
    return {
      launchers: Object.fromEntries(Object.keys(launchers).map((launcher) => [launcher, `${origin}/__tp_vite${launcher}`])),
      close: () => server.close(),
    };
  } catch (error) {
    await server.close();
    throw error;
  }
}

/** @internal Called by the native compiler while it holds the project build lock. */
export async function buildStyles({ root, styles }) {
  return publishFrontend({
    root: await realpath(root),
    inputs: styles.map((file, index) => [`style-${index}`, file]),
    directory: styleDirectory,
  });
}

async function publishFrontend({ root, inputs, directory, frameworks, plugins = [] }) {
  const publicDir = path.join(root, 'public');
  const typedpress = path.join(root, 'tp');
  const generated = path.join(typedpress, '_generated');
  await ensureDirectory(publicDir);
  await ensureDirectory(typedpress);
  await ensureDirectory(generated);

  const lock = path.join(generated, `.${directory}-lock`);
  await mkdir(lock).catch((error) => {
    if (error.code !== 'EEXIST') throw error;
    throw new Error(`Frontend build already running. If it stopped unexpectedly, check ${lock} before removing the lock.`);
  });
  try {
    const output = await compileFrontend({ root, inputs, publicDir, generated, directory, plugins });
    if (frameworks) {
      const state = path.join(root, '.tp');
      await ensureDirectory(state);
      const settings = Object.fromEntries(inputs.flatMap(([name, source]) =>
        output[name].scripts.map((launcher) => [launcher, normalizePath(source)])));
      const temp = path.join(state, `frontend-dev-${randomUUID()}.json`);
      try {
        await writeFile(temp, JSON.stringify({ launchers: settings, frameworks }));
        await rename(temp, path.join(state, 'frontend-dev.json'));
      } finally {
        await rm(temp, { force: true });
      }
    }
    return output;
  } finally {
    await rm(lock, { recursive: true });
  }
}

async function compileFrontend({ root, inputs, publicDir, generated, directory, plugins }) {
  const stylesOnly = directory === styleDirectory;
  const destination = path.join(publicDir, directory);
  const metadataName = stylesOnly ? 'frontend-styles.json' : 'frontend.ts';
  const metadataFile = path.join(generated, metadataName);
  const header = stylesOnly ? '{"generatedBy":"typedpress-frontend","styles":' : generatedHeader;
  const previous = await statIfPresent(destination);
  if (previous && (!previous.isDirectory() || !(await statIfPresent(path.join(destination, marker)))?.isFile())) {
    throw new Error(`public/${directory} is reserved for generated frontend files. Move the existing path first.`);
  }
  const previousMetadata = await statIfPresent(metadataFile);
  if (previousMetadata) {
    const metadata = previousMetadata.isFile() ? await readFile(metadataFile, 'utf8') : '';
    const contents = stylesOnly ? metadata : metadata.replace(/^\uFEFF/, '').replace('\r\n', '\n');
    if (!contents.startsWith(header)) {
      throw new Error(`tp/_generated/${metadataName} is reserved for generated metadata. Move the existing file first.`);
    }
  }

  const staging = await mkdtemp(path.join(generated, '.frontend-'));
  const output = path.join(staging, 'assets');
  const backup = path.join(staging, 'previous');
  let preserveBackup = false;
  try {
    if (inputs.length) await build({
      root,
      configFile: false,
      logLevel: stylesOnly ? 'warn' : 'info',
      base: './',
      publicDir: false,
      envPrefix: 'PUBLIC_',
      plugins: [tailwind(), ...plugins],
      oxc: { jsx: { runtime: 'automatic' } },
      resolve: frontendResolve(root),
      build: {
        outDir: output,
        manifest: true,
        reportCompressedSize: false,
        rolldownOptions: { input: Object.fromEntries(inputs.map(([name, file]) => [name, path.resolve(root, file)])) },
      },
    });

    const result = {};
    if (inputs.length) {
      const manifestFile = path.join(output, '.vite', 'manifest.json');
      const manifest = JSON.parse(await readFile(manifestFile, 'utf8'));
      if (!stylesOnly) await mkdir(path.join(output, 'entrypoints'));
      for (const [name, file] of inputs) {
        const source = file.split(path.sep).join('/');
        if (stylesOnly) {
          const entry = manifest[source];
          if (!entry?.isEntry || !entry.file.endsWith('.css')) {
            throw new Error(`Vite did not emit the stylesheet ${source}.`);
          }
          result[source] = `/${directory}/${entry.file}`;
        } else {
          result[name] = await entryMetadata(manifest, name, source, output);
        }
      }
      await rm(path.dirname(manifestFile), { recursive: true });
    } else {
      await mkdir(output);
    }
    await writeFile(path.join(output, marker), '');
    const metadata = path.join(staging, metadataName);
    if (stylesOnly) {
      await writeFile(metadata, `${header}${JSON.stringify(result)}}\n`);
    } else {
      await writeFile(metadata, `${header}export const frontend = ${JSON.stringify(result, null, 2)};\n`);
    }

    if (previous) await rename(destination, backup);
    try {
      await rename(output, destination);
      try {
        await rename(metadata, metadataFile);
      } catch (error) {
        await rename(destination, output);
        throw error;
      }
    } catch (error) {
      if (previous) {
        try {
          await rename(backup, destination);
        } catch (restoreError) {
          preserveBackup = true;
          throw new AggregateError([error, restoreError], `The previous frontend build is at ${backup}.`);
        }
      }
      throw error;
    }
    return result;
  } finally {
    if (!preserveBackup) await rm(staging, { recursive: true, force: true });
  }
}
