#!/usr/bin/env node
// Renames Zero v2 to First across this repository: file and directory moves with `git mv`,
// then text replacements in every tracked text file. Zero 0.8 names, which live Spaces still use,
// are kept (see KEEP and the path rules below). Every rule only matches a spelling of "zero", and
// no replacement produces one, so a second run changes nothing. Open branches rebase by merging
// main and running this again.
//
//   node scripts/rename-to-first.mjs            # move and rewrite, then print what changed
//   node scripts/rename-to-first.mjs --dry-run  # print what would change
//
// Generated files are listed in GENERATED and left alone here; regenerate them with their own
// generators afterwards (see the pull request that added this script).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
const dry = process.argv.includes('--dry-run');
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 });

// Not touched at all: third-party code (regenerated by scripts/vendor.sh), history, generated
// bundles and lock files (regenerated by their tools), and retained upstream provenance copies.
const SKIP = [
  /(^|\/)vendor-prefixed\//,
  /^docs\/decisions\//,
  /(^|\/)CHANGELOG\.md$/,
  /^docs\/benchmarks\//,
  /^runtime\/admin\/build\//,
  /^runtime\/identity\/build\//,
  /^runtime\/admin\/upstream-metadata\//,
  /(^|\/)package-lock\.json$/,
  /(^|\/)pnpm-lock\.yaml$/,
  /^Cargo\.lock$/,
  /(^|\/)composer\.lock$/,
  /^scripts\/rename-to-first\.mjs$/,
  // Zero 0.8 apps, captured as they were: the converter's inputs.
  /^tests\/fixtures\/app-migrate\//,
  /^tests\/fixtures\/config-migrate\/legacy-zero\.ts$/,
];
// Zero 0.8 prose: these keep saying "Zero" for 0.8. Code tokens (paths, the module name, the
// binary, prefixes) are still renamed, because the converter emits First code.
const ZERO_08_PROSE = [
  /^src\/config_migrate\//,
  /^docs\/migrating-from-zero\.md$/,
  /^docs\/zero-08-parity\.md$/,
  /^docs\/spec\/coexistence\.md$/,
  /^scripts\/census-08\//,
  /^tests\/wp\/legacy\//,
  /^tests\/wp\/app-migrate\//,
  /^tests\/app_migrate\.rs$/,
  /^tests\/php\/crypto-parity\//,
  /^runtime\/(Zero|First)\/Wp\/Legacy\//,
];
// Files where `_zero_<resource>_<field>` post meta is Zero 0.8 storage.
const ZERO_08_META = [/^tests\/wp\/legacy\//, /^runtime\/(Zero|First)\/Wp\/Legacy\//, /^docs\/migrating-from-zero\.md$/];
const CODE = /\.(rs|ts|tsx|mts|cts|mjs|js|cjs|jsx|php|sh|py|toml|ya?ml|json|jsonc|css|scss|sql)$|(^|\/)(Dockerfile|\.gitignore|gitignore)$/;

// Deny list: Zero 0.8 and production names that keep their spelling. Matched first and shielded.
const KEEP = [
  /formerly Zero v2/g,
  /@spacefast\/zero-compile\b/g,
  /@spacefast\/zero(?![\w-])(?:\/[\w.\/-]*)?/g, // the 0.8 SDK and its subpaths
  /(?:github\.com\/)?spacefast\/zero(?![\w-]|\/)(?:\.git)?/g, // the repository name
  /github\.com\/spacefast\/zero\b/g,
  /__spacefast\/zero\b/g, // engine-owned paths
  /\/__zero\/(?:auth|run|config|realtime\/)[\w\/*.<>-]*/g, // 0.8 paths
  /\blegacy\/zero-0\.8\b/g,
  /\bclient08\/zero-client\.js\b/g, // the 0.8 client bridge's file name
  /\bzero-0\.8(?:\.\d+)?\b/g,
  /\bzero-08\b/g,
  /\bzero08\b/g,
  /\bZ08_\w*/g,
  /\bZero 0\.\d[\w.]*/g,
  /\bruntime\.zero\.[\w.-]+/g, // 0.8 capability ids (runtime.zero.app-contract.v2 is the 0.8 capsule contract)
  /\bzero_realtime_events\b/g,
  /\bzero_generation\b/g,
  /\bzero_collection\b/g,
  /\bzero_declared\b/g,
  /\bzero_db_migration_statements\b/g,
  /\bzero_guest_upgrade_retry\b/g,
  /\b_zero_resource_id\b/g,
  /\bzero-all-features\b/g,
  /\blegacy-zero\b/g,
  /\bmigrating-from-zero\b/g,
  /\bstattic-zero[\w-]*/g,
  /\w*[sS]tatticZero\w*/g,
  /\w+ZeroCapsule\w*|\w*ZeroContentModel\w*|isZero(?:ProjectOnly|PublicStatic)Path/g,
  /"kind":\s*"zero"/g,
  /\bkind:\s*"zero"/g,
  /--from[ =]zero\b/g,
  /--runtime[ =]zero\b/g,
  /\bzero:check\b/g,
  /\bsf zero (?:abilities|call|queries|types|ls)\b/g, // `sf zero` commands that act on 0.8 Spaces
  /\bZERO_(?:CLIENT_MODULES|DYNAMIC_BLOCKS|SOURCE_CODE_EXTENSIONS|STRUCTURAL_COLLECTIONS|ORIGINAL|LEGACY_\w+)\b/g,
  // Monorepo paths that this repository only refers to.
  /\b(?:apps\/control-plane|runtime\/tests|runtime\/engine|e2e-tests|packages\/(?:zero|zero-compile|common|sdk))\/[\w.\/*-]*/g,
  /\bcrates\/stattic-[\w.\/-]*/g,
  // Zero 0.8 post meta (`_zero_<resource>_<field>`): see ZERO_08_META for the per-file rule.
  /\b_+zero_(?:projects|tasks|posts|pages_(?:title|content)|media_alt)\w*/g,
  // Arithmetic, not the product.
  /\b(?:non|signed|negative|toward|towards|leading|trailing|from)-zero\b/g,
  /\bzero-(?:width|length|based|terminated|int|cost|indexed|padded|fill|filled|copy|byte|value|sized|or-more)\b/g,
  /\bzero(?:s|es|ize|ized|ing|ed|vec|from|trie)\b/g,
  /\bRezo Zero\b/g,
  // Zero 0.8 values inside the converter: the `--from zero` source kind and the 0.8 physical
  // table-name fallback.
  /"zero" => Self::Zero/g,
  /if s\.is_empty\(\) \{ "zero"\.into\(\) \}/g,
  // A hash input: changing it would change every derived file uid (tests/fixtures/sync-file-uid.json).
  /\bzero-sync-file\b/g,
];
const KEEP_08_META = [/'_zero_'|\\\\?_zero\\\\?_%?|\b_+zero_\w*/g];

const COMMANDS = 'build|check|dev|migrate|migrate-legacy|migrate-legacy-users|migrate-spacefast|sync|doctor|abilities|deploy|sources|compile-sources|compile-to-store|help|wp|run|jobs|identity|publish-due|find|insert|update|delete|action|seed|pull|init|import|types|--help|--version|-h|-V|<command>|<site|<cmd>|\\.\\.\\.';
const MATH_BEFORE = /(?:division by|divided by|divisor is|negative|signed|non|is|be|are|was|to|toward|towards|than|or|of|returns?|at|exactly|with|by|equals?|becomes?|minus|plus|until|and|a|the|means|has|have|leaves?|gives?)\s+$/i;
const MATH_AFTER = /^\s*(?:errors?|failures?|limbs?|bits?|octets?|or more|or (?:one|positive|negative)|width|length|deps|dependencies|values?|digits?|fraction|rows|copies|cost|padding|items?|elements?|bytes?|times|exit|out of|percent|%|if\b|when\b|otherwise)/i;

/** Rules for every renamed text. Each `[pattern, replacement]` only matches a spelling of zero. */
const CODE_RULES = [
  // Whole phrases first.
  // The First compiler's own diagnostics, which the 0.8 converter matches.
  [/\bZero code\b/g, 'First code'],
  [/\bZero v2's\b/g, "First's"],
  [/\bZero v2\b/g, 'First'],
  [/\bzero[-_]v2(?=[-_.])[-_]?/g, 'first-'],
  [/\bzeroV2/g, 'first'],
  [/\bZeroV2/g, 'First'],
  [/\bZERO_V2_/g, 'FIRST_'],
  // HTTP paths First added under /__zero/.
  [/\/__zero\/(?=api\b|client\.js|client\.d\.ts|realtime\.js)/g, '/__first/'],
  // PHP namespace and classes.
  [/(?<![\w\\])Zero(?=\\)/g, 'First'],
  [/(?<=\\)Zero\b/g, 'First'],
  [/\b(namespace|use)(\s+)Zero\b/g, '$1$2First'],
  // Directory and file names.
  [/(?<![\w-])Zero(?=\/)/g, 'First'],
  [/(?<![\w-])(\.?)zero(?=\/)/g, '$1first'],
  [/(?<=\/)zero(?![\w\/-]|\.\d)/g, 'first'],
  [/(?<![\w.\/@-])zero(?=\.(?:config|gen|wasm|exe|mjs|rb|php|json|d\.ts|hosted|source-bundle)\b)/g, 'first'],
  [/\.zero(?=\.json\b)/g, '.first'],
  [/(?<![\w-])\.zero(?=[-\s"'`\/)]|$)/gm, '.first'],
  [/\bCARGO_BIN_EXE_zero\b/g, 'CARGO_BIN_EXE_first'],
  // Prefixes: zero_, zero__, __zero_, _zero_, wp_zero_, Zero_, ZERO_, zeroX, ZeroX.
  [/\bHTTP_(X_)?ZERO_/g, 'HTTP_$1FIRST_'],
  [/(?<![A-Za-z0-9_])ZERO_/g, 'FIRST_'],
  [/(?<![A-Za-z0-9_])Zero_/g, 'First_'],
  [/(?<![A-Za-z0-9])(_{1,2})zero(?=[_A-Z])/g, '$1first'],
  [/(?<=\b(?:wp|edit|edit_others|edit_published|delete|delete_others|delete_published|create|publish|read|read_private|group|field|rest_prepare|save_post)_)zero_/g, 'first_'],
  [/(?<![A-Za-z0-9_])zero_/g, 'first_'],
  [/(?<![A-Za-z0-9_$])zero(?=[A-Z])/g, 'first'],
  [/(?<![A-Za-z0-9_])Zero(?=[A-Z])/g, 'First'],
  // Hyphenated names: zero-admin, zero-pages, create-zero, X-Zero-Signature, ...
  [/(?<![\w-])zero-(?=[a-z<${*'"`])/g, 'first-'],
  [/\b(create|class|zz|x|single|hello|resolve|reject|base|such|nonexistent|fixture|spacefast)-zero\b/g, '$1-first'],
  [/\b(X|x)-Zero\b/g, '$1-First'],
  [/(?<![\w-])Zero-(?=[A-Za-z])/g, 'First-'],
  // Diagnostic codes.
  [/\bZ(\d{4})\b/g, 'F$1'],
  // The binary, the module and the WP-CLI command.
  [/\bwp(\s+(?:@\S+\s+)?)zero\b/g, 'wp$1first'],
  [/\bsf zero\b/g, 'sf first'],
  [/(?<=--bin[ =])zero\b/g, 'first'],
  [new RegExp(`(?<![\\w@.\\/\\\\-])zero(?=\\s+(?:${COMMANDS})(?![\\w-]))`, 'g'), 'first'],
  // The binary in messages: `for zero {command}`, `\nzero help`.
  [/(?<=\bfor )zero(?= \{)/g, 'first'],
  [/(?<=\\n)zero(?= (?:help|<command>))/g, 'first'],
  [/(?<=`)zero(?=[`\s])/g, 'first'],
  [/(?<=\[)zero(?=\])/g, 'first'],
  [/(\\?["'])zero\1/g, '$1first$1'],
  [/\bZERO\b/g, 'FIRST'],
];
// Prose and code: the product name as a word.
const PROSE_RULES = [[/(?<![\w\\-])Zero(?![\w\\])/g, 'First']];
// Lines that talk about Zero 0.8 keep "Zero" as a word.
const PROSE_08_LINE = /0\.[89]\b|\boriginal Zero|\bOriginal Zero|\bORIGINAL Zero|\bearlier Zero|Zero's last release|formerly Zero|\bthe new Zero|\bRezo Zero/;

function bareWord(text, prose08) {
  // A bare lowercase `zero` in code is the binary, the module or a variable named after them,
  // unless it is arithmetic. In Zero 0.8 code a plain "zero" string literal is a 0.8 value (the
  // `--from zero` source kind, 0.8 physical names); an escaped one is First code the converter emits.
  return text.replace(/(?<![A-Za-z0-9_@.\\\/-])zero(?![A-Za-z0-9_-]|\.\d)/g, (m, offset, all) => {
    const before = all.slice(Math.max(0, offset - 24), offset);
    const after = all.slice(offset + 4, offset + 30);
    return MATH_BEFORE.test(before) || MATH_AFTER.test(after) ? m : 'first';
  });
}

function shield(text, patterns, slots) {
  for (const pattern of patterns) {
    text = text.replace(pattern, (m) => `\u0000${slots.push(m) - 1}\u0001`);
  }
  return text;
}
const unshield = (text, slots) => {
  let previous;
  do {
    previous = text;
    text = text.replace(/\u0000(\d+)\u0001/g, (_, i) => slots[Number(i)]);
  } while (text !== previous);
  return text;
};

export function rename(text, path = '') {
  if (!/zero|Z\d{4}/i.test(text)) return text;
  const slots = [];
  let out = shield(text, KEEP, slots);
  if (ZERO_08_META.some((r) => r.test(path))) out = shield(out, KEEP_08_META, slots);
  const prose08 = ZERO_08_PROSE.some((r) => r.test(path));
  for (const [pattern, replacement] of CODE_RULES) {
    if (prose08 && replacement === '$1first$1') continue; // 0.8 source kinds such as --from "zero"
    out = out.replace(pattern, replacement);
  }
  if (path === '' || CODE.test(path)) out = bareWord(out, prose08);
  if (!prose08) {
    out = out
      .split('\n')
      .map((line) => (PROSE_08_LINE.test(unshield(line, slots)) ? line : PROSE_RULES.reduce((l, [p, r]) => l.replace(p, r), line)))
      .join('\n');
  }
  return unshield(out, slots);
}

// A path segment: the `zero/` app folder, `.zero/`, `runtime/Zero/`, `zero.config.ts`, `zero-admin.php`, ...
const KEEP_PATH = [/^src\/config_migrate\/app\/client08\//]; // the 0.8 client bridge keeps its file name
const renameSegment = (segment, path) =>
  KEEP_PATH.some((r) => r.test(path)) ? segment : segment === 'zero' ? 'first' : segment === '.zero' ? '.first' : segment === 'Zero' ? 'First' : rename(segment, path);
const renamePath = (path) =>
  path
    .split('/')
    .map((segment, i, all) => renameSegment(segment, all.slice(0, i + 1).join('/')))
    .join('/');

// The admin's upstream inventory records the SHA-256 of each adapted file. Its upstream digests
// don't change; the adapted hashes are refreshed after the rewrite.
function refreshAdminInventory(changed) {
  const file = join(root, 'runtime/admin/upstream-inventory.json');
  if (!existsSync(file)) return false;
  const before = readFileSync(file, 'utf8');
  const inventory = JSON.parse(before);
  const sha = (p) => createHash('sha256').update(readFileSync(join(root, 'runtime/admin', p))).digest('hex');
  for (const entry of inventory.files) {
    entry.adaptedSha256 = sha(entry.path);
    if (entry.retainedSourcePath === entry.path) entry.normalizedSha256 = entry.adaptedSha256;
  }
  const after = JSON.stringify(inventory, null, 2) + (before.endsWith('\n') ? '\n' : '');
  if (after === before) return false;
  if (!dry) writeFileSync(file, after);
  changed.push(['runtime/admin/upstream-inventory.json', 'refreshed adapted hashes']);
  return true;
}

function main() {
  const files = git('ls-files', '-z').split('\0').filter(Boolean);
  const skipped = (path) => SKIP.some((r) => r.test(path));
  // 1. Moves.
  const moves = [];
  for (const path of files) {
    if (skipped(path) && !/(^|\/)vendor-prefixed\//.test(path)) {
      // Skipped files still move with their directory (vendor-prefixed under runtime/Zero).
      const parent = renamePath(dirname(path));
      const moved = (parent === '.' ? '' : parent + '/') + path.split('/').pop();
      if (moved !== path) moves.push([path, moved]);
      continue;
    }
    const moved = /(^|\/)vendor-prefixed\//.test(path)
      ? path.replace(/^runtime\/Zero\//, 'runtime/First/')
      : renamePath(path);
    if (moved !== path) moves.push([path, moved]);
  }
  for (const [from, to] of moves) {
    if (dry) continue;
    mkdirSync(dirname(join(root, to)), { recursive: true });
    git('mv', '-k', '--', from, to);
  }
  // 2. Text.
  const changed = [];
  const current = dry ? files.map((p) => [p, moves.find(([f]) => f === p)?.[1] ?? p]) : git('ls-files', '-z').split('\0').filter(Boolean).map((p) => [p, p]);
  for (const [read, path] of current) {
    if (skipped(path)) continue;
    const full = join(root, read);
    if (!existsSync(full) || !lstatSync(full).isFile()) continue;
    const bytes = readFileSync(full);
    if (bytes.subarray(0, 8000).includes(0)) continue;
    const text = bytes.toString('utf8');
    const next = rename(text, path);
    if (next === text) continue;
    const count = text.split('\n').filter((line, i) => line !== next.split('\n')[i]).length;
    changed.push([path, `${count} line(s)`]);
    if (!dry) writeFileSync(full, next);
  }
  if (!dry) refreshAdminInventory(changed);
  for (const [from, to] of moves) console.log(`moved   ${from} -> ${to}`);
  for (const [path, what] of changed) console.log(`changed ${path} (${what})`);
  console.log(`${dry ? 'would move' : 'moved'} ${moves.length} file(s), ${dry ? 'would change' : 'changed'} ${changed.length} file(s)`);
  if (!dry && (moves.length || changed.length)) {
    console.log('Now regenerate: scripts/vendor.sh all (PHP 8.2), the admin and identity bundles, the WordPress catalog,');
    console.log('the example clients (`first build`), lock files, and rerun this script to confirm it changes nothing.');
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
