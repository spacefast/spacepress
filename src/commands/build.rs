const INDEX_PHP: &str = r#"<?php
declare(strict_types=1);
if (PHP_SAPI === 'cli-server' && is_file(__DIR__ . parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH)) && !str_ends_with(parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH), '.php')) {
    return false;
}
require __DIR__ . '/../zero/runtime/bootstrap.php';
\Zero\App::boot(dirname(__DIR__))->handleHttp();
"#;

struct Built {
    plugins: Option<wp_plugins::Config>,
    client_files: Vec<(String, Vec<u8>)>,
    schema: schema::Schema,
    functions_php: String,
    snapshot: serde_json::Value,
    migrations: Vec<(&'static str, String, String)>,
    gen_ts: String,
    warnings: Vec<String>,
    hints: Vec<String>,
}

pub(crate) fn validate_config(project: &Path, target: Target) -> Result<(), Diag> {
    build(project, Some(target)).map(|_| ())
}

/// Runs the whole pipeline in memory.
fn build(project: &Path, target: Option<Target>) -> Result<Built, Diag> {
    let entry = project.join("zero.config.ts");
    if !entry.is_file() {
        return Err(Diag::new(
            Span::NONE,
            format!("no zero.config.ts in {}", project.display()),
        ));
    }
    let program = loader::load(&entry)?;
    let mut ev = eval::Evaluator::new(&program);
    let config = ev.run()?;
    let config_span = Span {
        file: program.entry as u32,
        start: 0,
        end: 0,
    };
    let dir_name = project
        .file_name()
        .map(|n| extract::slugify_name(&n.to_string_lossy()))
        .unwrap_or_else(|| "app".into());
    let mut ext = extract::extract(&config, &mut ev, config_span, &dir_name, target)?;
    let mut schema = ext.schema.clone();
    let roots = std::mem::take(&mut ext.roots);
    let action_results;
    let (functions, slots) = {
        let mut c = compile::Compiler::new(&schema, &mut ev, &ext, &program);
        c.resolve_json_types()?;
        let slots = c.compile_roots(&roots)?;
        action_results = std::mem::take(&mut c.action_results);
        (std::mem::take(&mut c.output), slots)
    };
    for (slot, name) in slots {
        match slot {
            Slot::Hook { table, kind } => {
                schema
                    .collections
                    .get_mut(&table)
                    .expect("collection")
                    .hooks
                    .insert(kind, name);
            }
            Slot::Default { at } => schema.column_mut(&at).default = Some(DefaultKind::Fn(name)),
            Slot::OnUpdate { at } => schema.column_mut(&at).on_update = Some(DefaultKind::Fn(name)),
            Slot::Validate { at } => schema.column_mut(&at).rules.validate = Some(name),
            Slot::FieldAccess { at, op } => {
                schema.column_mut(&at).access.insert(op, Access::Fn(name));
            }
            Slot::JobHandler { job } => schema.jobs.get_mut(&job).expect("job").handler = name,
            Slot::ActionHandler { action } => schema.actions.get_mut(&action).expect("action").handler = name,
            Slot::Access { owner, op } => {
                let rule = Access::Fn(name);
                match owner {
                    Owner::Collection(t) => {
                        schema
                            .collections
                            .get_mut(&t)
                            .expect("collection")
                            .access
                            .insert(op, rule);
                    }
                    Owner::Global(g) => {
                        schema.globals.get_mut(&g).expect("global").access.insert(op, rule);
                    }
                    Owner::Action(a) => schema.actions.get_mut(&a).expect("action").access = rule,
                    Owner::FileBucket(f) => {
                        schema.files.get_mut(&f).expect("bucket").access.insert(op, rule);
                    }
                    Owner::Job(_) => unreachable!("jobs have no access rules"),
                }
            }
        }
    }
    // Hooks run in a fixed order per collection; sort for stable output.
    for c in schema.collections.values_mut() {
        c.hooks
            .sort_by_key(|k, _| schema::HookKind::ALL.iter().position(|h| h == k));
    }

    let functions_php = format!(
        "<?php\n\n// Generated by `zero build` from zero.config.ts. Do not edit.\n\ndeclare(strict_types=1);\n\nnamespace ZeroApp;\n\n{}",
        functions
    );
    let snapshot = migrate::snapshot(&schema);
    let prev = read_snapshot(project);
    let mut migrations = Vec::new();
    let warnings = migrate::destructive(&prev, &snapshot);
    for dialect in [migrate::Dialect::Sqlite, migrate::Dialect::Mysql] {
        let statements = migrate::plan(&prev, &snapshot, dialect);
        if statements.is_empty() {
            continue;
        }
        let dir = migrations_dir(project).join(dialect.dir());
        let n = next_migration_number(&dir);
        let name = if n == 1 { "init" } else { "update" };
        migrations.push((
            dialect.dir(),
            format!("{n:04}_{name}.sql"),
            migrate::render(&statements),
        ));
    }
    let client_files = client::files(&schema, &action_results, runtime_file);
    let gen_ts = schema_php::gen_ts(
        ext.register_name.unwrap_or("schema"),
        !schema.globals.is_empty() || !schema.jobs.is_empty(),
        schema.locales.as_ref(),
    );
    Ok(Built {
        plugins: ext.plugins,
        client_files,
        schema,
        functions_php,
        snapshot,
        migrations,
        gen_ts,
        warnings,
        hints: ext.hints,
    })
}

impl Built {
    fn summary(&self) -> String {
        let s = &self.schema;
        format!(
            "{} collections, {} globals, {} hooks, {} actions",
            s.collections.len(),
            s.globals.len(),
            s.collections.values().map(|c| c.hooks.len()).sum::<usize>(),
            s.actions.len()
        )
    }
}

fn migrations_dir(project: &Path) -> PathBuf {
    project.join("zero").join("migrations")
}

/// Moves v1's `zero/migrations/*.sql` into `zero/migrations/sqlite/` and upgrades its
/// snapshot to the shared v2 shape. Runs once: afterwards no `.sql` sits at the top level.
fn migrate_layout(project: &Path) -> std::io::Result<bool> {
    let dir = migrations_dir(project);
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return Ok(false);
    };
    let old_sql: Vec<PathBuf> = entries
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.is_file() && p.extension().is_some_and(|e| e == "sql"))
        .collect();
    if old_sql.is_empty() {
        return Ok(false);
    }
    let sqlite = dir.join("sqlite");
    std::fs::create_dir_all(&sqlite)?;
    for p in old_sql {
        std::fs::rename(&p, sqlite.join(p.file_name().expect("file name")))?;
    }
    let snapshot = dir.join("snapshot.json");
    if let Some(v1) = std::fs::read_to_string(&snapshot)
        .ok()
        .and_then(|s| serde_json::from_str::<serde_json::Value>(&s).ok())
        && v1["version"] != 2
    {
        std::fs::write(
            &snapshot,
            serde_json::to_string_pretty(&migrate::upgrade_v1_snapshot(&v1))? + "\n",
        )?;
    }
    Ok(true)
}

fn read_snapshot(project: &Path) -> serde_json::Value {
    let raw: Option<serde_json::Value> = std::fs::read_to_string(migrations_dir(project).join("snapshot.json"))
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok());
    match raw {
        Some(v) if v["version"] == 2 => v,
        Some(v) => migrate::upgrade_v1_snapshot(&v),
        None => serde_json::json!({ "version": 2, "tables": {} }),
    }
}

fn next_migration_number(dir: &Path) -> u32 {
    std::fs::read_dir(dir)
        .map(|entries| {
            entries
                .filter_map(|e| e.ok()?.file_name().to_str()?.get(..4)?.parse::<u32>().ok())
                .max()
                .unwrap_or(0)
        })
        .unwrap_or(0)
        + 1
}

fn write(path: &Path, content: impl AsRef<[u8]>) -> std::io::Result<()> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(path, content)
}

fn copy_dir(from: &Path, to: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(to)?;
    for entry in std::fs::read_dir(from)? {
        let entry = entry?;
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            std::fs::create_dir_all(&target)?;
            copy_dir(&entry.path(), &target)?;
        } else {
            std::fs::copy(entry.path(), target)?;
        }
    }
    Ok(())
}

fn copy_sql(from: &Path, to: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(to)?;
    if from.is_dir() {
        for entry in std::fs::read_dir(from)? {
            let entry = entry?;
            if entry.path().extension().is_some_and(|e| e == "sql") {
                std::fs::copy(entry.path(), to.join(entry.file_name()))?;
            }
        }
    }
    Ok(())
}

/// The runtime files a target ships, as (path inside the app, bytes).
fn runtime_for(target: Target) -> Vec<(String, &'static [u8])> {
    let mut out = Vec::new();
    for (rel, bytes) in runtime_files::FILES {
        if let Some(rest) = rel.strip_prefix("Zero/") {
            if target == Target::Standalone && rest.starts_with("Wp/") {
                continue;
            }
            out.push((format!("zero/runtime/{rest}"), *bytes));
        } else if let Some(rest) = rel.strip_prefix("bin/")
            && target == Target::Standalone
        {
            out.push((format!("zero/bin/{rest}"), *bytes));
        }
    }
    out
}

fn runtime_file(rel: &str) -> Option<&'static [u8]> {
    runtime_files::FILES.iter().find(|(p, _)| *p == rel).map(|(_, b)| *b)
}

/// Writes migrations, the snapshot, zero.gen.ts and the typed client into the project (committed).
fn emit_project(project: &Path, built: &Built) -> std::io::Result<()> {
    let migrations = migrations_dir(project);
    for (dir, name, sql) in &built.migrations {
        write(&migrations.join(dir).join(name), sql)?;
    }
    if !built.migrations.is_empty() || !migrations.join("snapshot.json").is_file() {
        write(
            &migrations.join("snapshot.json"),
            serde_json::to_string_pretty(&built.snapshot)? + "\n",
        )?;
    }
    write(&project.join("zero.gen.ts"), &built.gen_ts)?;
    let client_dir = project.join("zero").join("client");
    for (name, content) in &built.client_files {
        write(&client_dir.join(name), content)?;
    }
    Ok(())
}

/// Standalone app: `.zero/app` (disposable).
fn emit_standalone(project: &Path, out: &Path, built: &Built) -> std::io::Result<()> {
    std::fs::create_dir_all(out.join("data"))?;
    std::fs::create_dir_all(out.join("private"))?;
    let app_runtime = out.join("zero");
    if app_runtime.exists() {
        std::fs::remove_dir_all(&app_runtime)?;
    }
    for (rel, content) in runtime_for(Target::Standalone) {
        write(&out.join(rel), content)?;
    }
    write(&out.join("public/index.php"), INDEX_PHP)?;
    write(&out.join("zero/app/schema.php"), schema_php::render(&built.schema))?;
    write(&out.join("zero/app/functions.php"), &built.functions_php)?;
    copy_sql(
        &migrations_dir(project).join("sqlite"),
        &out.join("zero/app/migrations"),
    )?;
    let public = project.join("public");
    if public.is_dir() {
        copy_dir(&public, &out.join("public"))?;
    }
    Ok(())
}

/// Generated plugins are prepared in the same private tree as acquired dependencies.
fn emit_generated(project: &Path, plugins: &Path, built: &Built) -> std::io::Result<()> {
    let schema_php = schema_php::render(&built.schema);
    let vars = plugin_vars(&built.schema, &schema_php);
    for (slug, name) in [
        ("zero-runtime".to_string(), "zero-runtime"),
        (format!("zero-app-{}", built.schema.name), "zero-app"),
    ] {
        let directory = plugins.join(&slug);
        std::fs::create_dir_all(&directory)?;
        let template = runtime_file(&format!("wp-plugin/{name}.php")).expect("embedded plugin template");
        write(
            &directory.join(format!("{slug}.php")),
            substitute(&String::from_utf8_lossy(template), &vars),
        )?;
        // Deleting the plugin in wp-admin runs uninstall.php: options and capabilities go, content stays.
        let uninstall = runtime_file(&format!("wp-plugin/{name}-uninstall.php")).expect("embedded uninstall template");
        write(&directory.join("uninstall.php"), uninstall)?;
        write(
            &directory.join("readme.txt"),
            format!(
                "=== {slug} ===\nStable tag: {}\nLicense: GPL-2.0-or-later\n",
                env!("CARGO_PKG_VERSION")
            ),
        )?;
        if slug == "zero-runtime" {
            for (rel, bytes) in runtime_files::FILES {
                if let Some(rest) = rel.strip_prefix("Zero/") {
                    write(&directory.join("zero").join(rest), bytes)?;
                }
                if let Some(rest) = rel.strip_prefix("bin/") {
                    write(&directory.join("zero/bin").join(rest), bytes)?;
                }
            }
        } else {
            write(&directory.join("zero/app/schema.php"), &schema_php)?;
            if let Some(wpml) = crate::wpml_config::render(&built.schema) {
                write(&directory.join("wpml-config.xml"), wpml)?;
            }
            write(&directory.join("zero/app/functions.php"), &built.functions_php)?;
            copy_sql(
                &migrations_dir(project).join("wp"),
                &directory.join("zero/app/migrations"),
            )?;
            let public = project.join("public");
            if public.is_dir() {
                copy_dir(&public, &directory.join("public"))?;
            }
        }
    }
    for (rel, bytes) in runtime_files::FILES {
        if let Some(rest) = rel.strip_prefix("identity/") {
            write(&plugins.join("zero-identity").join(rest), bytes)?;
        }
    }
    Ok(())
}

fn zip_plugin(directory: &Path) -> std::io::Result<()> {
    use std::io::Write;
    fn append(writer: &mut zip::ZipWriter<std::fs::File>, root: &Path, dir: &Path) -> std::io::Result<()> {
        let mut entries = std::fs::read_dir(dir)?.collect::<Result<Vec<_>, _>>()?;
        entries.sort_by_key(|entry| entry.file_name());
        for entry in entries {
            let path = entry.path();
            if entry.file_type()?.is_dir() {
                append(writer, root, &path)?;
            } else if entry.file_type()?.is_file() {
                writer
                    .start_file(
                        path.strip_prefix(root).unwrap().to_string_lossy(),
                        zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated),
                    )
                    .map_err(std::io::Error::other)?;
                writer.write_all(&std::fs::read(&path)?)?;
            } else {
                return Err(std::io::Error::other(
                    "plugin trees cannot contain symlinks or special files",
                ));
            }
        }
        Ok(())
    }
    let mut writer = zip::ZipWriter::new(std::fs::File::create(directory.with_extension("zip"))?);
    append(&mut writer, directory.parent().unwrap(), directory)?;
    writer.finish().map_err(std::io::Error::other)?;
    Ok(())
}

/// Stage the complete artifact, publish it, then persist the sole dependency lock.
fn emit_wp_content(project: &Path, root: &Path, built: &Built) -> std::io::Result<PathBuf> {
    let empty = wp_plugins::Config { plugins: Vec::new() };
    let config = built.plugins.as_ref().unwrap_or(&empty);
    let plan = wp_plugins::resolve(config, &platform::plugins(built.schema.locales.is_some()))?;
    let parent = root
        .parent()
        .ok_or_else(|| std::io::Error::other("output needs a parent directory"))?;
    let parent = if parent.as_os_str().is_empty() {
        Path::new(".")
    } else {
        parent
    };
    std::fs::create_dir_all(parent)?;
    let parent = parent.canonicalize()?;
    let root = parent.join(
        root.file_name()
            .ok_or_else(|| std::io::Error::other("output needs a directory name"))?,
    );
    if project.starts_with(&root) || project.join("zero").starts_with(&root) {
        return Err(std::io::Error::other(
            "wp-content output cannot contain the project or its dependency lock",
        ));
    }
    struct Guard(PathBuf, std::fs::File);
    impl Drop for Guard {
        fn drop(&mut self) {
            let _ = self.1.sync_all();
            let _ = std::fs::remove_file(&self.0);
        }
    }
    fn guard(path: PathBuf) -> std::io::Result<Guard> {
        let file = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
            .map_err(|e| std::io::Error::other(format!("cannot acquire build lock {}: {e}", path.display())))?;
        Ok(Guard(path, file))
    }
    let lock = project.join("zero/wp-plugins.lock.json");
    std::fs::create_dir_all(lock.parent().unwrap())?;
    // Serialize the project lockfile and publication to a shared output root.
    let _project_guard = guard(project.join("zero/.wp-plugins.build.lock"))?;
    let _output_guard = guard(parent.join(format!(
        ".{}.zero-build.lock",
        root.file_name().unwrap().to_string_lossy()
    )))?;
    let prepared = wp_plugins::Prepared::acquire(&plan, &lock, &platform::cache(project))?;
    let temp = tempfile::tempdir_in(&parent)?;
    let stage = temp.path().join("wp-content");
    if std::fs::symlink_metadata(&root).is_ok() {
        if !std::fs::symlink_metadata(&root)?.is_dir() {
            return Err(std::io::Error::other("output root must be a real directory"));
        }
        wp_plugins::copy_output(&root, &stage)?;
    } else {
        std::fs::create_dir(&stage)?;
    }
    prepared.install_into(&stage.join("plugins"))?;
    let plugins = stage.join("plugins");
    for entry in std::fs::read_dir(&plugins)? {
        let entry = entry?;
        if entry.file_name().to_string_lossy().starts_with("zero-") {
            if entry.file_type()?.is_dir() {
                std::fs::remove_dir_all(entry.path())?;
            } else {
                std::fs::remove_file(entry.path())?;
            }
        }
    }
    emit_generated(project, &plugins, built)?;
    let mut versions = serde_json::Map::new();
    for slug in [
        "zero-runtime".to_string(),
        "zero-identity".to_string(),
        format!("zero-app-{}", built.schema.name),
    ] {
        let directory = plugins.join(&slug);
        php_lint_tree(&directory)?;
        zip_plugin(&directory)?;
        let version = if slug.starts_with("zero-app-") {
            format!(
                "{}+{}",
                env!("CARGO_PKG_VERSION"),
                plugin_vars(&built.schema, &schema_php::render(&built.schema))
                    .into_iter()
                    .find(|(key, _)| *key == "schemaHash")
                    .unwrap()
                    .1
            )
        } else {
            env!("CARGO_PKG_VERSION").to_string()
        };
        versions.insert(slug, version.into());
    }
    for dependency in prepared.dependencies() {
        versions.insert(dependency.slug.clone(), dependency.version.clone().into());
    }
    let requires: serde_json::Map<String, serde_json::Value> = platform::plugins(built.schema.locales.is_some())
        .into_iter()
        .map(|plugin| (plugin.slug, format!(">={}", plugin.version).into()))
        .collect();
    write(
        &stage.join("zero-manifest.json"),
        serde_json::to_string_pretty(
            &serde_json::json!({"zero":env!("CARGO_PKG_VERSION"),"runtime":platform::SERIES,"app":built.schema.name,"plugins":versions,"requires":requires,"dependencies":prepared.dependencies().collect::<Vec<_>>(),"locales":built.schema.locales}),
        )? + "\n",
    )?;
    let lock_bytes = prepared.lock_bytes()?;
    std::fs::create_dir_all(lock.parent().unwrap())?;
    let mut lock_file = tempfile::NamedTempFile::new_in(lock.parent().unwrap())?;
    std::io::Write::write_all(&mut lock_file, &lock_bytes)?;
    let backup = temp.path().join("previous");
    let existed = root.exists();
    if existed {
        std::fs::rename(&root, &backup)?;
    }
    if let Err(e) = std::fs::rename(&stage, &root) {
        if existed {
            std::fs::rename(&backup, &root)?;
        }
        return Err(e);
    }
    if let Err(e) = lock_file.persist(&lock) {
        std::fs::remove_dir_all(&root)?;
        if existed {
            std::fs::rename(&backup, &root)?;
        }
        return Err(e.error);
    }
    let legacy = project.join(".zero/wp");
    if !root.starts_with(&legacy) && legacy.is_dir() {
        std::fs::remove_dir_all(legacy)?;
    }
    Ok(root)
}

fn plugin_vars(schema: &schema::Schema, schema_php: &str) -> Vec<(&'static str, String)> {
    let hash = {
        // FNV-1a: a stable fingerprint of the built schema (changes when the plugin must migrate).
        let mut h: u64 = 0xcbf2_9ce4_8422_2325;
        for b in schema_php.bytes() {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0100_0000_01b3);
        }
        format!("{h:016x}")
    };
    let label = schema::title_case(&schema.name);
    vec![
        ("name", schema.name.clone()),
        ("slug", format!("zero-app-{}", schema.name)),
        ("runtimeSeries", platform::SERIES.to_string()),
        ("wpVersion", platform::WORDPRESS.to_string()),
        ("phpVersion", platform::PHP.to_string()),
        (
            "requires",
            if schema.locales.is_some() {
                "secure-custom-fields, action-scheduler, mcp-adapter, zero-runtime, polylang"
            } else {
                "secure-custom-fields, action-scheduler, mcp-adapter, zero-runtime"
            }
            .to_string(),
        ),
        ("label", label.clone()),
        ("Name", label),
        ("version", env!("CARGO_PKG_VERSION").to_string()),
        ("schemaHash", hash),
        ("zeroVersion", env!("CARGO_PKG_VERSION").to_string()),
    ]
}

/// `{{key}}` → value. Unknown placeholders are left as they are.
fn substitute(text: &str, vars: &[(&str, String)]) -> String {
    let mut out = text.to_string();
    for (k, v) in vars {
        out = out.replace(&format!("{{{{{k}}}}}"), v);
    }
    out
}

fn php_lint(files: &[PathBuf]) -> Result<(), String> {
    for path in files {
        let result = std::process::Command::new("php").arg("-l").arg(path).output();
        match result {
            Ok(o) if o.status.success() => {}
            Ok(o) => {
                return Err(format!(
                    "{}{}",
                    String::from_utf8_lossy(&o.stdout),
                    String::from_utf8_lossy(&o.stderr)
                ));
            }
            Err(_) => return Ok(()), // no PHP on this machine: skip the lint
        }
    }
    Ok(())
}

pub(super) fn run(args: &crate::Args) -> ExitCode {
    let project = args.project.canonicalize().unwrap_or(args.project.clone());
    if !matches!(args.command.as_str(), "build" | "check" | "dev") {
        eprintln!("unknown command {}\n{USAGE}", args.command);
        return ExitCode::from(2);
    }
    let started = std::time::Instant::now();
    let target = if args.wp { Some(Target::Wp) } else { args.target };
    let built = match build(&project, target) {
        Ok(b) => b,
        Err(d) => {
            eprint!("{}", diag::render(&d, &project));
            return ExitCode::from(1);
        }
    };
    if args.command == "check" {
        // The config is target-independent: one evaluation covers both targets' rules. Building the
        // other target too proves both schema.php variants render.
        let other = if built.schema.target == Target::Wp {
            Target::Standalone
        } else {
            Target::Wp
        };
        if let Err(d) = build(&project, Some(other)) {
            eprint!("{}", diag::render(&d, &project));
            return ExitCode::from(1);
        }
        if !args.quiet {
            for h in &built.hints {
                eprintln!("hint: {h}");
            }
        }
        println!("ok: {} ({:.0?})", built.summary(), started.elapsed());
        return ExitCode::SUCCESS;
    }

    let migrated_layout = match migrate_layout(&project) {
        Ok(m) => m,
        Err(e) => {
            eprintln!("error: couldn't move zero/migrations into zero/migrations/sqlite: {e}");
            return ExitCode::from(1);
        }
    };
    // Rebuild after moving the layout: the snapshot is read from the new place.
    let built = if migrated_layout {
        match build(&project, target) {
            Ok(b) => b,
            Err(d) => {
                eprint!("{}", diag::render(&d, &project));
                return ExitCode::from(1);
            }
        }
    } else {
        built
    };
    if let Err(e) = emit_project(&project, &built) {
        eprintln!("error: couldn't write migrations or the client: {e}");
        return ExitCode::from(1);
    }
    // A project that syncs commits its sync bases, and nothing else under .zero (design §5.4).
    if built.schema.collections.values().any(|c| c.sync.is_some())
        && let Err(e) = crate::sync::git::ignore_build_output(&project)
    {
        eprintln!("error: {e}");
        return ExitCode::from(1);
    }
    let (out, lint) = match built.schema.target {
        Target::Standalone => {
            let out = args.out.clone().unwrap_or_else(|| project.join(".zero").join("app"));
            if let Err(e) = emit_standalone(&project, &out, &built) {
                eprintln!("error: couldn't write the app: {e}");
                return ExitCode::from(1);
            }
            let lint = vec![out.join("zero/app/schema.php"), out.join("zero/app/functions.php")];
            (out, lint)
        }
        Target::Wp => {
            let root = args.out.clone().unwrap_or_else(|| project.join(".zero/wp-content"));
            match emit_wp_content(&project, &root, &built) {
                Ok(directory) => (directory, Vec::new()),
                Err(error) => {
                    eprintln!("error: couldn't write wp-content: {error}");
                    return ExitCode::from(1);
                }
            }
        }
    };
    if let Err(e) = php_lint(&lint) {
        eprintln!("error: generated PHP failed `php -l` (this is a Zero bug):\n{e}");
        return ExitCode::from(1);
    }
    for w in &built.warnings {
        eprintln!("warning: this migration {w}");
    }
    if !args.quiet {
        for h in &built.hints {
            eprintln!("hint: {h}");
        }
    }
    if migrated_layout {
        println!("moved zero/migrations/*.sql to zero/migrations/sqlite/");
    }
    let shown = out.strip_prefix(&project).unwrap_or(&out).display().to_string();
    let new: Vec<String> = built
        .migrations
        .iter()
        .map(|(d, n, _)| format!("zero/migrations/{d}/{n}"))
        .collect();
    let suffix = if new.is_empty() {
        String::new()
    } else {
        format!(" (new migrations {})", new.join(", "))
    };
    println!(
        "built {} for {} -> {shown}{suffix} in {:.0?}",
        built.summary(),
        built.schema.target.name(),
        started.elapsed()
    );
    if args.command == "dev" {
        return if built.schema.target == Target::Wp {
            super::dev::wp(&out, args.port)
        } else {
            super::dev::standalone(&out, args.port)
        };
    }
    ExitCode::SUCCESS
}

fn php_lint_tree(directory: &Path) -> std::io::Result<()> {
    let mut php = Vec::new();
    fn collect(directory: &Path, files: &mut Vec<PathBuf>) -> std::io::Result<()> {
        for entry in std::fs::read_dir(directory)? {
            let entry = entry?;
            if entry.file_type()?.is_dir() && entry.file_name() != "vendor-prefixed" {
                collect(&entry.path(), files)?;
            } else if entry.path().extension().is_some_and(|extension| extension == "php") {
                files.push(entry.path());
            }
        }
        Ok(())
    }
    collect(directory, &mut php)?;
    php_lint(&php).map_err(std::io::Error::other)
}
